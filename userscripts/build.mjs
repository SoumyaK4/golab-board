import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const read = name => readFile(new URL(`src/${name}`, import.meta.url), 'utf8');
const metadata = `// ==UserScript==
// @name         Go Lab enhancements
// @namespace    https://github.com/SoumyaK4/golab-board
// @version      1.0.0
// @description  Responsive Go Lab UI, mouse navigation, accessible controls and local rule-aware score estimates.
// @author       Soumya Kundu
// @license      MIT
// @match        https://golab.gg/*
// @match        https://*.golab.gg/*
// @match        http://localhost/*
// @match        http://127.0.0.1/*
// @run-at       document-end
// @sandbox      raw
// @grant        none
// @noframes
// ==/UserScript==`;

const assets = [['STYLE', 'style.css'], ['HOME', 'home.html'], ['HEADER', 'header.html'], ['FOOTER', 'footer.html']];
const modules = ['ownership.mjs', 'scoring.mjs', 'score-view.mjs', 'layout.mjs', 'enhancements.mjs'];
const license = await readFile(new URL('../LICENSE', import.meta.url), 'utf8');
const parts = [metadata, `/*\n${license.trim()}\n*/`, '// Generated by node userscripts/build.mjs. Edit userscripts/src instead.', '(function () {', "'use strict';"];
for (const [name, path] of assets) parts.push(`const ${name} = ${JSON.stringify(await read(path))};`);
for (const path of modules) {
    const source = (await read(path)).replace(/^import .* from '\.\/[^']+';\r?\n/gm, '').replace(/^export (?=(?:async )?(?:function|class|const) )/gm, '');
    parts.push(`\n// Source: ${path}\n${source}`);
}
parts.push('})();\n');
const output = new URL('golab-enhancements.user.js', import.meta.url);
const result = parts.join('\n');
if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== result) throw new Error('Userscript is stale: run node userscripts/build.mjs');
    console.log('Generated userscript is up to date.');
} else {
    await writeFile(output, result);
    console.log(`Built ${fileURLToPath(output)} (${Buffer.byteLength(result)} bytes)`);
}
